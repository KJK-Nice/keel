func TestDirectSafeAllowsPlainReads(t *testing.T) {
	safe := []string{
		`ls`,
		`ls -la /var/log`,
		`ls -lh --color=auto`,
		`pwd`,
		`whoami`,
		`id -u`,
		`uptime`,
		`uname -a`,
		`hostname -f`,
		`date`,
		`date -u '+%Y-%m-%d'`,
		`df -h`,
		`du -sh /var/log`,
		`free -h`,
		`cat /etc/os-release`,
		`head -n 20 /var/log/syslog`,
		`tail -50 /var/log/syslog`,
		`grep -i 'error|warn' /var/log/syslog`,
		`grep -rn --include='*.go' 'func main' .`,
		`ps aux`,
		`ps aux | grep nginx`,
		`ps -ef | grep -v grep | head -5`,
		`ss -ltnp`,
		`ss -ltnp 'sport = :5432'`,
		`echo keel-agent-ok`,
		`echo 'hello world'`,
		`echo "a b"`,
		`wc -l /etc/passwd`,
		`sort -n f | uniq -c | sort -rn | head`,
		`systemctl --no-pager status nginx`,
		`journalctl --no-pager -u nginx -n 50`,
		`docker ps -a`,
		`docker logs --tail 50 web`,
		`kubectl get pods -A`,
		`kubectl get pods -n kube-system -o wide`,
		`kubectl logs -n app web-1 --tail 100`,
		`ip -br a`,
		`ip addr show dev eth0`,
		`ip route`,
		`lsblk`,
		`ping -c 3 example.com`,
		`which kubectl`,
		`stat -c '%s' f`,
		`printenv HOME PATH`,
		`cat /etc/hosts`,
	}
	for _, c := range safe {
		if !DirectSafe(c) {
			t.Errorf("DirectSafe(%q) = false, want a direct type", c)
		}
	}
}
